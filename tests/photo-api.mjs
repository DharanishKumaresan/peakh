import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const base = 'http://127.0.0.1:5180';
const image = await readFile(new URL('./fixtures/profile.jpg', import.meta.url));
const user = 'photo-test-' + crypto.randomUUID(), peer = 'photo-peer-' + crypto.randomUUID();
const request = (who, path, options = {}) => fetch(base + path, { ...options, headers: { ...(who ? { 'oai-authenticated-user-id': who } : {}), ...options.headers } });
const social = async who => (await request(who, '/api/social')).json();
const change = (who, method, body) => request(who, '/api/social', { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
const upload = who => request(who, '/api/profile/photo', { method: 'PUT', headers: { 'Content-Type': 'image/jpeg' }, body: image });
assert.equal((await upload(null)).status,401);
const self = (await social(user)).self, friend = (await social(peer)).self;
const saved = await upload(user); assert.equal(saved.status,200,await saved.clone().text());
const first = (await saved.json()).photoUrl; assert.ok(first);
assert.equal((await social(user)).self.photoUrl,first);
const ownPhoto=await request(user,first);assert.equal(ownPhoto.status,200);assert.equal(ownPhoto.headers.get('content-type'),'image/jpeg');assert.deepEqual(Buffer.from(await ownPhoto.arrayBuffer()),image);
assert.equal((await request(null,first)).status,401);
assert.equal((await request(peer,first)).status,404);
assert.equal((await change(user,'POST',{code:friend.code})).status,201);
assert.equal((await request(peer,first)).status,404);
const pending=(await social(peer)).requests[0];
assert.equal((await change(peer,'PATCH',{action:'accept',id:pending.id})).status,200);
assert.equal((await request(peer,first)).status,200);
assert.equal((await social(peer)).friends[0].photoUrl,first);
assert.equal((await (await request(peer,'/api/friends/'+self.id)).json()).photoUrl,first);
const replaced=await upload(user);assert.equal(replaced.status,200);assert.notEqual((await replaced.json()).photoUrl,first);
assert.equal((await change(peer,'PATCH',{action:'remove',id:self.id})).status,200);
assert.equal((await request(peer,first)).status,404);
assert.equal((await request(user,'/api/profile/photo',{method:'DELETE'})).status,200);
assert.equal((await social(user)).self.photoUrl,null);
assert.equal((await request(user,first)).status,404);
assert.equal((await request(user, '/api/profile/photo', { method:'PUT', headers:{'Content-Type':'image/jpeg'}, body:'not an image' })).status,400);
assert.equal((await request(user, '/api/profile/photo', { method:'PUT', headers:{'Content-Type':'image/svg+xml'}, body:'<svg/>' })).status,415);
// A read lets Wrangler's local proxy recover after rejecting an unread request body.
await social(user);
assert.equal((await request(user, '/api/profile/photo', { method:'PUT', headers:{'Content-Type':'image/jpeg'}, body:Buffer.alloc(524289) })).status,413);
console.log('PASS: photo upload, replacement, removal, validation, persistence, and friend-only access.');
